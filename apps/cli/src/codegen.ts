import type { ArgSpec, AttrSpec, CapSpec, DeviceSpec } from '@sebastian/dsl';
import type { ModelResponse } from '@sebastian/protocol';

/**
 * `seb pull` codegen: turns the Worker's model (devices + capability definitions) into
 * `generated/home.generated.ts` — typed handles for every device and mode at the location.
 * Device IDs live only in the private home repo, never in this one.
 */

interface JsonSchema {
  type?: string;
  enum?: unknown[];
  properties?: Record<string, JsonSchema>;
}

interface CapabilityDefinition {
  attributes?: Record<string, { schema?: JsonSchema }>;
  commands?: Record<
    string,
    { arguments?: { name: string; optional?: boolean; schema?: JsonSchema }[] }
  >;
}

function attrSpec(schema: JsonSchema | undefined): AttrSpec {
  const value = schema?.properties?.value;
  const unit = schema?.properties?.unit?.enum?.[0];
  if (value?.enum?.length && value.enum.every((v) => typeof v === 'string')) {
    return { type: 'enum', values: value.enum as string[] };
  }
  switch (value?.type) {
    case 'integer':
      return { type: 'number', integer: true, ...(typeof unit === 'string' ? { unit } : {}) };
    case 'number':
      return { type: 'number', ...(typeof unit === 'string' ? { unit } : {}) };
    case 'string':
      return { type: 'string' };
    case 'boolean':
      return { type: 'boolean' };
    default:
      return { type: 'json' };
  }
}

function argSpec(a: { name: string; optional?: boolean; schema?: JsonSchema }): ArgSpec {
  const s = a.schema ?? {};
  const opt = a.optional ? { optional: true } : {};
  if (s.enum?.length && s.enum.every((v) => typeof v === 'string')) {
    return { name: a.name, type: 'enum', values: s.enum as string[], ...opt };
  }
  const type =
    s.type === 'integer' || s.type === 'number' || s.type === 'string' || s.type === 'boolean'
      ? s.type
      : 'json';
  return { name: a.name, type, ...opt };
}

export function capSpec(def: unknown): CapSpec {
  const d = (def ?? {}) as CapabilityDefinition;
  const attributes: Record<string, AttrSpec> = {};
  for (const [name, a] of Object.entries(d.attributes ?? {})) attributes[name] = attrSpec(a.schema);
  const commands: Record<string, ArgSpec[]> = {};
  for (const [name, c] of Object.entries(d.commands ?? {}))
    commands[name] = (c.arguments ?? []).map(argSpec);
  return { attributes, commands };
}

const RESERVED = new Set([
  'Home',
  'Devices',
  'default',
  'import',
  'export',
  'const',
  'class',
  'function',
]);

/** "Pantry door" → pantryDoor; "Hue Bridge 1" → hueBridge1. Unique within `taken`. */
export function identifier(label: string, taken: Set<string>): string {
  const words = label
    .normalize('NFKD')
    .replace(/[^\w\s]/g, ' ')
    .split(/[\s_]+/)
    .filter(Boolean);
  let id = words
    .map((w, i) =>
      i === 0 ? w.toLowerCase() : w.charAt(0).toUpperCase() + w.slice(1).toLowerCase(),
    )
    .join('');
  if (!id || /^\d/.test(id) || RESERVED.has(id))
    id = `device${id ? id.charAt(0).toUpperCase() + id.slice(1) : ''}`;
  let out = id;
  for (let n = 2; taken.has(out); n++) out = `${id}${n}`;
  taken.add(out);
  return out;
}

export function generate(m: ModelResponse, now = new Date()): string {
  const rooms = new Map(m.rooms.map((r) => [r.roomId, r.name]));
  const hubs = new Map(m.hubs.map((h) => [h.hubId, h.name]));
  const modes: Record<string, string> = {};
  for (const mode of m.modes)
    modes[modes[mode.name] ? `${mode.name} (${mode.id.slice(0, 4)})` : mode.name] = mode.id;

  const taken = new Set<string>();
  const lines: string[] = [
    `// Generated by \`seb pull\` on ${now.toISOString()} for location "${m.location.name}".`,
    '// Do not edit: re-run `seb pull` after adding, renaming or removing devices.',
    "import { defineDevice, defineLocation } from '@sebastian/dsl';",
    '',
    `export const Home = defineLocation(${JSON.stringify(
      {
        id: m.location.locationId,
        name: m.location.name,
        timeZoneId: m.location.timeZoneId,
        modes,
      },
      null,
      2,
    )});`,
    '',
  ];
  const names: string[] = [];
  const sorted = [...m.devices].sort((a, b) => a.label.localeCompare(b.label));
  for (const d of sorted) {
    if (d.integrationType === 'HUB') continue;
    const components: Record<string, Record<string, CapSpec>> = {};
    for (const c of d.components) {
      const caps: Record<string, CapSpec> = {};
      for (const cap of c.capabilities)
        caps[cap.id] = capSpec(m.capabilities[`${cap.id}/${cap.version}`]);
      components[c.id] = caps;
    }
    if (!components.main) continue;
    const room = d.roomId ? rooms.get(d.roomId) : undefined;
    const spec: DeviceSpec = {
      id: d.deviceId,
      label: d.label,
      ...(room ? { room } : {}),
      integrationType: d.integrationType,
      ...(d.hubId ? { hubId: d.hubId } : {}),
      components: components as DeviceSpec['components'],
    };
    const name = identifier(d.label, taken);
    names.push(name);
    const where = [d.integrationType, d.hubId ? (hubs.get(d.hubId) ?? 'hub') : 'no hub', spec.room]
      .filter(Boolean)
      .join(' · ');
    lines.push(`/** ${d.label.replace(/\*\//g, '* /')} — ${where} */`);
    lines.push(`export const ${name} = defineDevice(${JSON.stringify(spec, null, 2)});`, '');
  }
  lines.push(`export const Devices = { ${names.join(', ')} };`, '');
  return lines.join('\n');
}
